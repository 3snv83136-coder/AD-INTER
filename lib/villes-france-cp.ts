export function searchVillesFrance(query: string, limit = 8): VilleVar[] {
  const q = normalize(query)
  if (!q) return []
  const digits = query.trim().replace(/\s+/g, "")
  return VILLES_FRANCE
    .filter((v) => normalize(v.nom).includes(q) || (digits.length >= 2 && v.cp.startsWith(digits)))
    .sort((a, b) => {
      const aCp = digits.length >= 2 && a.cp.startsWith(digits)
      const bCp = digits.length >= 2 && b.cp.startsWith(digits)
      if (aCp && !bCp) return -1
      if (!aCp && bCp) return 1
      if (aCp && bCp) return a.cp.localeCompare(b.cp)
      const an = normalize(a.nom)
      const bn = normalize(b.nom)
      const aStarts = an.startsWith(q)
      const bStarts = bn.startsWith(q)
      if (aStarts && !bStarts) return -1
      if (!aStarts && bStarts) return 1
      return a.nom.localeCompare(b.nom, "fr")
    })
    .slice(0, limit)
}
